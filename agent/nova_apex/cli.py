import sys
import asyncio

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.prompt import Prompt
from nova_apex.core.engine import engine
from nova_apex.core.logger import agent_logger
from nova_apex.core.memory import agent_memory
from nova_apex.skills.web_account_creator import web_account_creator
from nova_apex.skills.doc_generator import doc_generator
from nova_apex.skills.system_admin import system_admin
from nova_apex.config.settings import settings

console = Console()

def print_banner():
    banner = """[bold cyan]
    _  _  _____  _  _   __     ____  ____  ____  _  _ 
   ( \( )(  _  )( \/ ) / _\   (  _ \(  __)(  _ \( \/ )
    )  (  )(_)(  \  / /    \   ) _ ( ) _)  ) __/ )  ( 
   (_/\_)(_____)  \/  \_/\_/  (____/(____)(__)  (_/\_)
[/bold cyan]
[bold bright_white]   UNIVERSAL AUTONOMOUS AUTOMATION OS & COMPUTER-USE AGENT[/bold bright_white]
[dim]   Cross-Domain Engine: Web Browser | Desktop GUI | Mobile ADB | Terminal Shell[/dim]
    """
    console.print(banner)

async def run_interactive_cli():
    print_banner()

    telemetry = system_admin.get_system_telemetry()
    console.print(Panel(
        f"[green]● System Operational[/green] | OS: [bold]{telemetry['os']} {telemetry['architecture']}[/bold] | Free Disk: [bold]{telemetry['free_disk_gb']} GB[/bold]\n"
        f"Workspace: [cyan]{telemetry['workspace']}[/cyan]\n"
        f"Controllers: [blue]Playwright Stealth[/blue] | [magenta]Desktop PyAutoGUI[/magenta] | [yellow]Mobile ADB[/yellow] | [white]PowerShell[/white]",
        title="[bold cyan]NOVA-APEX TELEMETRY[/bold cyan]",
        border_style="cyan"
    ))

    while True:
        console.print("\n[bold]Select an action:[/bold]")
        console.print("  [cyan]1[/cyan] - Execute Autonomous Mission (Natural Language Goal)")
        console.print("  [cyan]2[/cyan] - Automated Web Account Generator (Target URL)")
        console.print("  [cyan]3[/cyan] - Scaffold Full-Stack Project / Files in Workspace")
        console.print("  [cyan]4[/cyan] - Desktop & OS Screen Audit")
        console.print("  [cyan]5[/cyan] - View Credentials & Account Vault")
        console.print("  [cyan]6[/cyan] - Start Mission Control Web Dashboard")
        console.print("  [cyan]0[/cyan] - Exit")

        choice = Prompt.ask("\nEnter choice", default="1")

        if choice == "0":
            console.print("[yellow]Exiting NOVA-APEX...[/yellow]")
            break

        elif choice == "1":
            goal_prompt = Prompt.ask("\n[bold cyan]Enter mission objective[/bold cyan]")
            if goal_prompt.strip():
                with console.status("[bold green]NOVA-APEX executing mission...[/bold green]"):
                    goal = await engine.run_goal(goal_prompt)
                
                table = Table(title="Mission Execution Summary")
                table.add_column("Step", justify="center", style="cyan")
                table.add_column("Milestone", style="white")
                table.add_column("Domain", style="magenta")
                table.add_column("Status", justify="center")

                for s in goal.steps:
                    st_color = "green" if s.status.value == "success" else "red"
                    table.add_row(str(s.step_id), s.title, s.domain.value, f"[{st_color}]{s.status.value.upper()}[/{st_color}]")
                console.print(table)

        elif choice == "2":
            url = Prompt.ask("\nEnter signup portal URL", default="https://github.com/signup")
            email = Prompt.ask("Enter an email address you control")
            username = Prompt.ask("Optional username (leave blank to skip)", default="")
            with console.status(f"[bold cyan]Preparing signup details for review at {url}...[/bold cyan]"):
                res = await web_account_creator.create_account(url, custom_username=username or None, email=email)
            if res.get("success"):
                console.print(Panel(
                    f"[bold green]Signup form prepared for review[/bold green]\n"
                    f"Submitted: No\nDetails: {res.get('details')}\n"
                    "Review the website, enter any remaining fields, and submit manually.",
                    border_style="green",
                ))
            else:
                console.print(Panel(f"[bold red]Signup preparation stopped:[/bold red] {res.get('error') or res.get('message')}", border_style="red"))

        elif choice == "3":
            proj_name = Prompt.ask("\nEnter project folder name", default="apex_app")
            structure = {
                "README.md": f"# {proj_name}\n\nAutomated project generated by NOVA-APEX.",
                "src/main.py": "print('Hello from NOVA-APEX automated workspace!')\n",
                "config/app_config.json": '{\n  "version": "1.0.0",\n  "environment": "production"\n}\n',
                "docs/architecture.md": "# System Architecture\n\nModular design pattern."
            }
            res = doc_generator.create_project_scaffold(proj_name, structure)
            console.print(Panel(f"[bold green]Project scaffolded![/bold green] Root: {res['root_path']}\nFiles: {res['files_count']}", border_style="green"))

        elif choice == "4":
            from nova_apex.controllers.desktop_controller import desktop_controller
            shot = desktop_controller.take_screenshot("cli_audit")
            console.print(Panel(f"[bold green]Desktop state captured:[/bold green] {shot}", border_style="green"))

        elif choice == "5":
            accounts = agent_memory.vault.get("created_accounts", [])
            if not accounts:
                console.print("[dim]Vault empty. No credentials generated yet.[/dim]")
            else:
                vt = Table(title="Saved Accounts Vault")
                vt.add_column("Service", style="cyan")
                vt.add_column("Username", style="yellow")
                vt.add_column("Timestamp", style="dim")
                for a in accounts:
                    vt.add_row(a.get("service"), a.get("username"), a.get("timestamp"))
                console.print(vt)

        elif choice == "6":
            import uvicorn
            console.print(f"[bold green]Launching Mission Control Web Server at http://localhost:{settings.server_port}...[/bold green]")
            from nova_apex.server.app import app
            uvicorn.run(app, host=settings.server_host, port=settings.server_port)

def main():
    asyncio.run(run_interactive_cli())

if __name__ == "__main__":
    main()
