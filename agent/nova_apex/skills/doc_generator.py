import os
from pathlib import Path
from typing import Dict, Any, List
from datetime import datetime
from nova_apex.config.settings import settings
from nova_apex.core.logger import agent_logger

class DocumentGeneratorSkill:
    """
    Autonomous high-level skill:
    Generates structured project directories, reports, documentation, manifests, and source code.
    """

    def create_project_scaffold(self, project_name: str, structure: Dict[str, str]) -> Dict[str, Any]:
        """
        Takes a dict of {relative_path: content} and scaffolds the entire project tree.
        """
        base_dir = settings.workspace_dir / project_name
        base_dir.mkdir(parents=True, exist_ok=True)
        created_files = []

        agent_logger.info(f"Scaffolding project '{project_name}' in workspace...", domain="SKILL")

        for rel_path, content in structure.items():
            target = base_dir / rel_path
            target.parent.mkdir(parents=True, exist_ok=True)
            with open(target, "w", encoding="utf-8") as f:
                f.write(content)
            created_files.append(str(target))

        agent_logger.success(f"Scaffolded {len(created_files)} files in {base_dir}", domain="SKILL")
        return {
            "project_name": project_name,
            "root_path": str(base_dir),
            "files_count": len(created_files),
            "files": created_files
        }

    def generate_report(self, title: str, sections: List[Dict[str, str]]) -> str:
        """
        Generates a markdown audit/execution report.
        """
        filename = f"Report_{title.replace(' ', '_')}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.md"
        out_path = settings.artifacts_dir / filename

        lines = [
            f"# {title}",
            f"**Generated by NOVA-APEX Universal Automation Engine**",
            f"**Timestamp:** {datetime.utcnow().isoformat()}",
            "\n---\n"
        ]

        for sec in sections:
            lines.append(f"## {sec.get('heading', 'Section')}")
            lines.append(sec.get('body', ''))
            lines.append("")

        content = "\n".join(lines)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)

        agent_logger.success(f"Generated comprehensive report: {out_path}", domain="SKILL")
        return str(out_path)

doc_generator = DocumentGeneratorSkill()
